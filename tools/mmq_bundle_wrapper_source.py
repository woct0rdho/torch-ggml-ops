def _grouped_entry(symbol: str, arguments: str, values: str, call: str) -> str:
    return f"""extern "C" __launch_bounds__(torch_ggml_ops::ck::BACKWARD_THREADS, 2) __global__
void {symbol}(
{arguments}) {{
    {call}(
{values});
}}
"""


def _render_grouped_backward(symbol: str, config: GroupedBackwardConfig) -> str:
    prefix = _PREAMBLE + '#include "ck/grouped_mmq_backward.cuh"\n\n'
    kind = config.kind
    if kind == GroupedBackwardKind.GENERIC_SINGLE:
        quant_type = _cpp_quant(config.quant_type)
        return (
            prefix
            + f"""extern "C" __launch_bounds__(torch_ggml_ops::ck::GROUPED_BACKWARD_THREADS, 1) __global__
void {symbol}(
        const __hip_bfloat16 * __restrict__ grad_output,
        const char * __restrict__ packed_weight,
        __hip_bfloat16 * __restrict__ grad_input,
        const int64_t * __restrict__ expert_indices,
        const int32_t * __restrict__ expert_offsets,
        int num_experts,
        int rows,
        int out_features,
        int in_features,
        int blocks_per_weight_row,
        int64_t bytes_per_expert) {{
    torch_ggml_ops::ck::grouped_mmq_grad_input_body<{quant_type}>(
        grad_output,
        packed_weight,
        grad_input,
        expert_indices,
        expert_offsets,
        num_experts,
        rows,
        out_features,
        in_features,
        blocks_per_weight_row,
        bytes_per_expert);
}}
"""
        )

    if kind == GroupedBackwardKind.GENERIC_PAIR:
        quant_type = _cpp_quant(config.quant_type)
        return (
            prefix
            + f"""extern "C" __launch_bounds__(torch_ggml_ops::ck::GROUPED_BACKWARD_THREADS, 1) __global__
void {symbol}(
        const __hip_bfloat16 * __restrict__ first_grad_output,
        const __hip_bfloat16 * __restrict__ second_grad_output,
        const char * __restrict__ first_packed_weight,
        const char * __restrict__ second_packed_weight,
        __hip_bfloat16 * __restrict__ grad_input,
        const int64_t * __restrict__ expert_indices,
        const int32_t * __restrict__ expert_offsets,
        int num_experts,
        int rows,
        int out_features,
        int in_features,
        int blocks_per_weight_row,
        int64_t bytes_per_expert) {{
    torch_ggml_ops::ck::grouped_mmq_pair_grad_input_body<{quant_type}>(
        first_grad_output,
        second_grad_output,
        first_packed_weight,
        second_packed_weight,
        grad_input,
        expert_indices,
        expert_offsets,
        num_experts,
        rows,
        out_features,
        in_features,
        blocks_per_weight_row,
        bytes_per_expert);
}}
"""
        )

    if kind == GroupedBackwardKind.FIXED_Q8_0_GENERIC:
        return (
            prefix
            + f"""extern "C" __launch_bounds__(torch_ggml_ops::ck::GROUPED_BACKWARD_THREADS, 1) __global__
void {symbol}(
{_FIXED_ARGUMENTS}) {{
    torch_ggml_ops::ck::fixed_grouped_q8_0_grad_input_body(
        grad_output,
        packed_weight,
        grad_input,
        tokens,
        out_features,
        bytes_per_group);
}}
"""
        )

    if kind == GroupedBackwardKind.FIXED_Q8_0_M256:
        return (
            prefix
            + f"""extern "C" __launch_bounds__(torch_ggml_ops::ck::BACKWARD_THREADS, 1) __global__
void {symbol}(
{_FIXED_ARGUMENTS}) {{
    torch_ggml_ops::ck::fixed_grouped_q8_0_grad_input_tiled_body<4, 16, 0>(
        grad_output,
        packed_weight,
        grad_input,
        tokens,
        bytes_per_group);
}}
"""
        )

    if kind == GroupedBackwardKind.TUNED_FIXED_Q8_0:
        return (
            prefix
            + f"""extern "C" __launch_bounds__(torch_ggml_ops::ck::BACKWARD_THREADS, 2) __global__
void {symbol}(
{_FIXED_ARGUMENTS}) {{
    torch_ggml_ops::ck::fixed_grouped_q8_0_grad_input_tiled_body<
        {config.m_tiles_per_wave}, 16, 0>(
        grad_output,
        packed_weight,
        grad_input,
        tokens,
        bytes_per_group);
}}
"""
        )

    if kind == GroupedBackwardKind.TUNED_DEEPSEEK_PAIR:
        return prefix + _grouped_entry(
            symbol,
            _PAIR_ARGUMENTS,
            _PAIR_VALUES,
            "torch_ggml_ops::ck::grouped_mmq_pair_grad_input_deepseek_body<"
            f"GGML_TYPE_IQ2_XXS, 2048, 4096, 16, {config.m_tiles_per_wave}, true>",
        )

    call = _SPECIAL_GROUPED_CALLS.get(kind)
    if call is None:
        raise ValueError(f"unsupported grouped backward kind {kind}")
    if kind in _PAIR_KINDS:
        return prefix + _grouped_entry(symbol, _PAIR_ARGUMENTS, _PAIR_VALUES, call)
    if kind in _ROW_TASK_KINDS:
        return prefix + _grouped_entry(
            symbol, _ROW_TASK_ARGUMENTS, _ROW_TASK_VALUES, call
        )
    return prefix + _grouped_entry(symbol, _SINGLE_ARGUMENTS, _SINGLE_VALUES, call)


def render_wrapper(symbol: str, config: KernelConfig) -> str:
    """Return one concrete source file with no build-selector macros."""
    if isinstance(config, ForwardConfig):
        return _render_forward(symbol, config)
    if isinstance(config, DenseBackwardConfig):
        return _render_dense_backward(symbol, config)
    if isinstance(config, GroupedBackwardConfig):
        return _render_grouped_backward(symbol, config)
    raise TypeError(f"unsupported MMQ kernel config {type(config).__name__}")
